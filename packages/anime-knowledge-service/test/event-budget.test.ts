import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { estimateChatTokens, estimateModelTokens, type KnowledgeEventResolutionRequest } from "@kita/contracts";
import { BangumiStore } from "../src/kb/store.js";
import { ContextBudgetError, resolveEventWithKnowledge } from "../src/pipelines/event.js";

const documentId = "11111111-1111-4111-8111-111111111111";

function request(content = "Anime Expo features Example Anime."): KnowledgeEventResolutionRequest {
  return {
    baseline: {
      schemaVersion: "event-content-bundle/v2",
      event: {
        name: "Anime Expo 2026", alternateNames: [], eventType: "CONVENTION", description: "",
        startDate: "2026-07-02", endDate: "2026-07-05", timezone: "America/Los_Angeles",
        venue: { name: "Los Angeles Convention Center", addressLine1: "", city: "Los Angeles", region: "CA", postalCode: "", countryCode: "US" },
        officialUrl: "https://www.anime-expo.org/", organizerNames: [],
      },
      links: [], facts: [], ticketOffers: [], exhibitors: [], sessions: [], guests: [], updates: [], activities: [], relatedSubjects: [],
      relations: [], media: [],
      evidence: [{ field: "event.name", sourceDocumentId: documentId, method: "crawler-assertion", quote: "Anime Expo 2026", confidence: 0.98 }],
      conflicts: [], warnings: ["Generated by deterministic fallback; relationships and ambiguous fields require review."], confidence: 0.9,
    },
    evidence: {
      crawlRun: { id: "run", sourceName: "Anime Expo Official", rootUrl: "https://www.anime-expo.org/" },
      documents: [{ id: documentId, url: "https://www.anime-expo.org/", title: "Anime Expo 2026", pageType: "EVENT", assertions: [], chunks: [{ content }], media: [] }],
    },
  };
}

async function storeWithSubjects(count = 20): Promise<BangumiStore> {
  const directory = await mkdtemp(path.join(os.tmpdir(), "kita-event-budget-"));
  const lines = Array.from({ length: count }, (_, index) => JSON.stringify({ id: index + 1, type: 2, name: `Example Anime ${index + 1}`, nameCn: "", aliases: [] })).join("\n");
  await writeFile(path.join(directory, "subjects.jsonl"), `${lines}\n`);
  const store = new BangumiStore(directory);
  await store.load();
  return store;
}

test("single-pass event enrichment remains inside the configured prompt budget", async () => {
  const store = await storeWithSubjects();
  const prompts: Array<{ system: string; user: string }> = [];
  const llm = {
    enabled: true,
    modelName: "test",
    providerName: "test",
    async json(system: string, user: string) {
      prompts.push({ system, user });
      return { value: { event: {}, relatedSubjects: [], relations: [], sessions: [], guests: [], activities: [], warnings: [] }, inputTokens: 1_500, outputTokens: 500 };
    },
  };

  const budget = 2_000;
  const result = await resolveEventWithKnowledge(request(), store, llm, "test-v1", budget);
  assert.equal(prompts.length, 1);
  assert.ok(prompts.every((prompt) => estimateChatTokens(prompt.system, prompt.user) <= budget));
  assert.ok(result.metrics.knowledgeCandidates < 20);
  assert.ok(result.metrics.estimatedInputTokens <= budget);
  assert.equal(result.model.promptVersion, "event-enrichment-patch-v6");
  assert.deepEqual(result.result.warnings, []);
});

test("oversized direct API evidence fails before calling the model", async () => {
  const store = await storeWithSubjects(1);
  let calls = 0;
  const llm = { enabled: true, modelName: "test", providerName: "test", async json() { calls += 1; return { value: {} }; } };
  await assert.rejects(
    resolveEventWithKnowledge(request("evidence ".repeat(20_000)), store, llm, "test-v1", 2_000),
    ContextBudgetError,
  );
  assert.equal(calls, 0);
});

test("an oversized deterministic baseline is projected and restored instead of causing 413", async () => {
  const input = request();
  input.baseline.sessions = Array.from({ length: 120 }, (_, index) => ({
    externalKey: `session:${index}`,
    title: `Anime Expo Session ${index}`,
    sessionType: "PANEL" as const,
    description: `Detailed session description ${index}. `.repeat(80),
    startDate: null,
    endDate: null,
    timezone: "America/Los_Angeles",
    venueName: "Los Angeles Convention Center",
    room: `Room ${index}`,
    ageRating: "",
    organizationNames: [],
    subjectTargets: [],
    personTargets: [],
    imageMediaCandidateId: null,
    tags: [],
    sourceDocumentIds: [documentId],
    confidence: 0.8,
  }));
  assert.ok(estimateModelTokens(input.baseline) > 24_000);

  const prompts: Array<{ system: string; user: string }> = [];
  const llm = {
    enabled: true,
    modelName: "test",
    providerName: "test",
    async json(system: string, user: string) {
      prompts.push({ system, user });
      return { value: { event: {}, relatedSubjects: [], relations: [], sessions: [], guests: [], activities: [], warnings: [] }, inputTokens: 2_000, outputTokens: 500 };
    },
  };

  const result = await resolveEventWithKnowledge(input, await storeWithSubjects(1), llm, "test-v1", 24_000);
  assert.equal(prompts.length, 1);
  assert.ok(prompts.every((prompt) => estimateChatTokens(prompt.system, prompt.user) <= 24_000));
  assert.ok((result.metrics.baselineSourceTokens || 0) > 24_000);
  assert.ok((result.metrics.baselineTokens || Infinity) <= 8_000);
  assert.equal(result.result.sessions.length, 120);
});
